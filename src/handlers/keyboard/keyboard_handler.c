char last_char = 0;
static int shift = 0;
static int capslock = 0;
static int numlock = 0;

void keyboard_handler() {
    //kprintf("A!\n");
    uint8_t scancode = inb(0x60);
    if (scancode == 0x2A || scancode == 0x36) {
        shift = 1;
    } else if (scancode == 0xAA || scancode == 0xB6) {
        shift = 0;
    } else if (scancode == 0x3A) {
        if (!capslock) { capslock = 1; } else { capslock = 0; }
    } else if (scancode == 0x45) {
        if (!numlock) { numlock = 1; } else { numlock = 0; }
    } else {
        if (scancode > 0x58) { lapic_write(0xB0, 0); return; }
        if (shift) {
            if (numlock)
                last_char = scancode_shift_map_with_numlock[scancode];
            else
                last_char = scancode_shift_map[scancode];
        } else if (capslock) {
            if (numlock)
                last_char = scancode_capslock_map_with_numlock[scancode];
            else
                last_char = scancode_capslock_map[scancode];
        } else {
            if (numlock)
                last_char = scancode_map_with_numlock[scancode];
            else
                last_char = scancode_map[scancode];
        }
    }
    lapic_write(0xB0, 0);
}
